#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <locale.h>

int main() {
    setlocale(LC_CTYPE, "RUS");

    float area;           // площадь территории (км²)
    float population;     // число жителей (чел.)
    float density;        // плотность населения (чел./км²)

    printf("=== РАСЧЕТ ПЛОТНОСТИ НАСЕЛЕНИЯ ===\n\n");

    // Ввод исходных данных
    printf("Введите площадь территории (кв/км): ");
    scanf("%f", &area);

    printf("Введите число жителей (чел.): ");
    scanf("%f", &population);

    // Проверка деления на ноль
    if (area == 0) {
        printf("\nОшибка! Площадь территории не может быть равна нулю.\n");
        return 1;
    }

    // Вычисление плотности населения
    density = population / area;

    // Вывод результатов
    printf("\n===============================================\n");
    printf("         РЕЗУЛЬТАТЫ РАСЧЕТА\n");
    printf("===============================================\n\n");
    printf("Площадь территории:    %10.2f кв/км\n", area);
    printf("Число жителей:         %10.2f чел.\n", population);
    printf("-----------------------------------------------\n");
    printf("ПЛОТНОСТЬ НАСЕЛЕНИЯ:   %10.2f чел./км²\n", density);
    printf("===============================================\n\n");

    return 0;
}